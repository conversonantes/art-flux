import { z } from "zod";

export const FINDING_KINDS = ["found", "missing"] as const;
/** `found`: "Qué encontramos"; `missing`: "Qué faltó". */
export type FindingKind = (typeof FINDING_KINDS)[number];

/**
 * What a fragment holds: plain text with a few marks (**bold**, "- " lists, ==highlight==) that
 * the screens render. The core stores it as written.
 */
export const fragmentTextSchema = z
  .string()
  .trim()
  .min(1, "Escribe algo antes de guardar")
  .max(4000, "El texto es muy largo");

export const fragmentKindSchema = z.enum(FINDING_KINDS, { error: "Elige si es lo que encontraron o lo que faltó" });

/**
 * One contribution to the finding of an approach. Several people write fragments of the same
 * approach; each one is theirs alone to edit.
 */
export interface FindingFragment {
  /** Generated by the client, so saving the same one twice (a retry) is not a duplicate. */
  id: string;
  approachId: string;
  authorId: string;
  kind: FindingKind;
  text: string;
  createdAt: Date;
  updatedAt: Date;
}
