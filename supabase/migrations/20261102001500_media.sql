-- Material (HU-13): photos, voice notes, files, links and written notes registered in an obra,
-- optionally tied to one of its sessions and to one approach. Files live in R2 (never in the
-- database): the row keeps only the path and is "pending" until the client confirms the upload.
-- Rows are written by the registering member; confirming and removing go through functions
-- (see decisions/0006), so nothing here is updatable directly.

create table public.media (
  id               uuid primary key, -- generated by the client: registering twice is the same material
  group_id         uuid not null references public.groups (id),
  project_id       uuid not null references public.projects (id),
  session_id       uuid references public.sessions (id),
  approach_id      uuid references public.approaches (id),
  kind             text not null check (kind in ('photo', 'audio', 'document', 'link', 'note')),
  title            text check (title is null or char_length(title) <= 120),
  path             text,
  mime             text,
  size_bytes       bigint,
  duration_seconds integer check (duration_seconds is null or duration_seconds between 1 and 180),
  url              text check (url is null or char_length(url) <= 2000),
  body             text check (body is null or char_length(body) <= 4000),
  status           text not null default 'pending' check (status in ('pending', 'uploaded')),
  created_by       uuid not null references public.profiles (id),
  created_at       timestamptz not null default now(),
  deleted_at       timestamptz,
  -- Each kind carries exactly what it needs.
  constraint media_file_kinds check (
    kind not in ('photo', 'audio', 'document')
    or (path is not null and mime is not null and size_bytes between 1 and 20971520 and url is null and body is null)
  ),
  constraint media_link_kind check (kind <> 'link' or (url is not null and path is null and body is null)),
  constraint media_note_kind check (
    kind <> 'note' or (body is not null and char_length(btrim(body)) >= 1 and path is null and url is null)
  ),
  constraint media_status_by_kind check (kind in ('photo', 'audio', 'document') or status = 'uploaded')
);

create index media_project_idx on public.media (project_id, created_at) where deleted_at is null;
create index media_session_idx on public.media (session_id) where deleted_at is null;
create index media_approach_idx on public.media (approach_id) where deleted_at is null;

-- Helpers (security definer, so the policies do not depend on the caller reading those tables).
create function public.session_project_id(p_session uuid)
returns uuid
language sql stable security definer set search_path = public
as $$
  select project_id from public.sessions where id = p_session and deleted_at is null;
$$;

create function public.approach_session_id(p_approach uuid)
returns uuid
language sql stable security definer set search_path = public
as $$
  select session_id from public.approaches where id = p_approach and deleted_at is null;
$$;

alter table public.media enable row level security;

-- Everyone in the group reads uploaded material; a pending upload is only its author's.
create policy media_select on public.media
  for select using (
    deleted_at is null
    and public.is_member(public.current_user_id(), group_id)
    and (status = 'uploaded' or created_by = public.current_user_id())
  );

-- Register as yourself, in an obra of your group; session and approach must belong to that obra.
create policy media_insert on public.media
  for insert with check (
    created_by = public.current_user_id()
    and public.is_member(public.current_user_id(), group_id)
    and public.project_group_id(project_id) = group_id
    and (
      (kind in ('photo', 'audio', 'document') and status = 'pending')
      or (kind in ('link', 'note') and status = 'uploaded')
    )
    and (session_id is null or (
      public.session_group_id(session_id) = group_id and public.session_project_id(session_id) = project_id
    ))
    and (approach_id is null or (
      public.approach_group_id(approach_id) = group_id
      and public.session_project_id(public.approach_session_id(approach_id)) = project_id
      and (session_id is null or session_id = public.approach_session_id(approach_id))
    ))
  );

revoke all on public.media from authenticated;
grant select, insert on public.media to authenticated;

-- The author confirms the file reached R2. Errors: P0004 not allowed.
create function public.confirm_media(p_media uuid)
returns public.media
language plpgsql security definer set search_path = public
as $$
declare
  v_user uuid := public.current_user_id();
  v_media public.media;
begin
  if v_user is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;

  select * into v_media from public.media where id = p_media and deleted_at is null for update;
  if not found or v_media.created_by <> v_user then
    raise exception 'confirm_not_allowed' using errcode = 'P0004';
  end if;

  update public.media set status = 'uploaded' where id = p_media returning * into v_media;
  return v_media;
end;
$$;

revoke all on function public.confirm_media(uuid) from public;
grant execute on function public.confirm_media(uuid) to authenticated;

-- Soft delete: the author, or an admin of the group. Errors: P0004 not allowed.
create function public.remove_media(p_media uuid)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_user uuid := public.current_user_id();
  v_media public.media;
begin
  if v_user is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;

  select * into v_media from public.media where id = p_media and deleted_at is null for update;
  if not found or not (v_media.created_by = v_user or public.is_admin(v_user, v_media.group_id)) then
    raise exception 'remove_not_allowed' using errcode = 'P0004';
  end if;

  update public.media set deleted_at = now() where id = p_media;
end;
$$;

revoke all on function public.remove_media(uuid) from public;
grant execute on function public.remove_media(uuid) to authenticated;
