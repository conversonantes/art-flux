-- Findings (hallazgos, HU-12): what a session's approach found and what was missing, written in
-- fragments. Each fragment is a row with its own author, so several people can write at once
-- without overwriting each other and the screen can color by author.
-- Rules: only after the session was held; any member adds fragments; only the author edits or
-- removes their own.

create table public.finding_fragments (
  id          uuid primary key, -- generated by the client: saving the same id twice is the same fragment
  approach_id uuid not null references public.approaches (id),
  author_id   uuid not null references public.profiles (id),
  kind        text not null check (kind in ('found', 'missing')),
  text        text not null check (char_length(btrim(text)) between 1 and 4000),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  deleted_at  timestamptz
);

create index finding_fragments_approach_idx
  on public.finding_fragments (approach_id, created_at) where deleted_at is null;

-- Group and state of the approach's session; security definer so policies do not depend on the
-- caller being able to read approaches or sessions.
create function public.approach_group_id(p_approach uuid)
returns uuid
language sql stable security definer set search_path = public
as $$
  select s.group_id
  from public.approaches a join public.sessions s on s.id = a.session_id
  where a.id = p_approach and a.deleted_at is null and s.deleted_at is null;
$$;

create function public.approach_session_is_completed(p_approach uuid)
returns boolean
language sql stable security definer set search_path = public
as $$
  select coalesce((
    select s.status = 'completed'
    from public.approaches a join public.sessions s on s.id = a.session_id
    where a.id = p_approach and a.deleted_at is null and s.deleted_at is null
  ), false);
$$;

alter table public.finding_fragments enable row level security;

create policy finding_fragments_select on public.finding_fragments
  for select using (
    deleted_at is null and public.is_member(public.current_user_id(), public.approach_group_id(approach_id))
  );

create policy finding_fragments_insert on public.finding_fragments
  for insert with check (
    author_id = public.current_user_id()
    and public.is_member(public.current_user_id(), public.approach_group_id(approach_id))
    and public.approach_session_is_completed(approach_id)
  );

-- Only the author edits their fragment, and only its text.
create policy finding_fragments_update on public.finding_fragments
  for update using (author_id = public.current_user_id())
  with check (
    author_id = public.current_user_id()
    and public.is_member(public.current_user_id(), public.approach_group_id(approach_id))
    and public.approach_session_is_completed(approach_id)
  );

revoke all on public.finding_fragments from authenticated;
grant select, insert on public.finding_fragments to authenticated;
grant update (text, updated_at) on public.finding_fragments to authenticated;

-- Soft delete by function (a plain UPDATE of deleted_at cannot pass RLS; see decisions/0006).
-- Only the author. Errors: P0004 not allowed.
create function public.remove_finding_fragment(p_fragment uuid)
returns void
language plpgsql security definer set search_path = public
as $$
declare
  v_user uuid := public.current_user_id();
begin
  if v_user is null then
    raise exception 'not authenticated' using errcode = '28000';
  end if;

  if not exists (
    select 1 from public.finding_fragments where id = p_fragment and author_id = v_user and deleted_at is null
  ) then
    raise exception 'remove_not_allowed' using errcode = 'P0004';
  end if;

  update public.finding_fragments set deleted_at = now() where id = p_fragment;
end;
$$;

revoke all on function public.remove_finding_fragment(uuid) from public;
grant execute on function public.remove_finding_fragment(uuid) to authenticated;
